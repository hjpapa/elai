import {Grid,polygon,rounded,saveHires} from './c12-common.mjs';
function ring(g,cx,cy,rx,ry,color){for(let y=Math.floor(cy-ry);y<=cy+ry;y++)for(let x=Math.floor(cx-rx);x<=cx+rx;x++){const d=((x-cx)/rx)**2+((y-cy)/ry)**2;if(d<=1.12&&d>=.52)g.set(x,y,color);}}
function table(f){
 const g=new Grid(64,96);
 // 네 다리와 가로대. 넓은 바닥 구조이므로 별도의 발밑 그림자는 없어요.
 polygon(g,[[11,48],[17,50],[17,79],[12,81]],'X','U');
 polygon(g,[[47,50],[53,48],[52,80],[47,78]],'U','Q');
 g.line(13,53,13,77,'t').line(49,54,49,77,'X');
 polygon(g,[[12,76],[32,86],[51,76],[51,81],[32,91],[12,81]],'U','Q');
 g.line(14,77,31,85,'T').line(33,87,49,79,'X');
 polygon(g,[[27,57],[34,59],[34,91],[28,91]],'X','U');g.line(29,61,29,89,'t');
 polygon(g,[[5,46],[32,32],[59,46],[32,60]],'t','U');
 polygon(g,[[5,46],[32,60],[32,65],[5,51]],'T','U');
 polygon(g,[[32,60],[59,46],[59,51],[32,65]],'e','E');
 g.line(7,47,30,59,'Z').line(34,60,56,49,'X');
 g.line(9,49,27,58,'X').line(36,61,49,54,'U');
 // 나무틀 안 미로 판. 작은 글자 대신 바위·길·깃발·로봇으로 보여요.
 polygon(g,[[10,45],[32,34],[54,45],[32,56]],'G','F');
 polygon(g,[[13,45],[32,36],[51,45],[32,54]],'W','*');
 const at=(x,y)=>({x:32+(x-y)*5,y:38+(x+y)*2.5});
 for(let i=1;i<4;i++){
  const a=at(i,0),b=at(i,4),c=at(0,i),d=at(4,i);g.line(a.x,a.y,b.x,b.y,'*').line(c.x,c.y,d.x,d.y,'*');
 }
 // 바위는 뒤쪽에 놓아 앞 로봇을 가리지 않아요.
 for(const[x,y]of[[1,0],[1,1],[2,2]]){const p=at(x+.5,y+.5);polygon(g,[[p.x-3,p.y-2],[p.x,p.y-4],[p.x+3,p.y-2],[p.x+3,p.y+1],[p.x,p.y+2],[p.x-3,p.y]],'S','d');g.line(p.x-2,p.y-2,p.x,p.y-3,'a');g.line(p.x,p.y,p.x+2,p.y-1,'f');}
 // 깃발 발치의 물결만 작게/크게 바뀌어요. 탁자와 깃발 위치는 고정이에요.
 if(f===0){ring(g,44,44,4,2,'C');g.set(44,43,'q');}
 else{ring(g,44,44,7,3,'C');ring(g,44,44,3,1,'q');}
 g.line(44,31,44,44,'U').line(45,32,45,42,'t');
 polygon(g,[[46,31],[54,34],[46,37]],'r','R');g.line(47,32,50,33,'K');
 // 작은 로봇 모형에는 두 눈과 받침을 남겨요.
 g.ellipse(23,49,5,2,'d');rounded(g,19,40,8,8,'i','d');
 g.line(20,41,25,41,'j');rounded(g,20,42,6,4,'m','d');g.set(21,43,'q').set(24,43,'q');
 g.line(22,38,22,40,'S').set(22,37,'Y').line(21,48,25,48,'f');
 return g;
}

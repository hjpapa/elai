// C13-2: 두 유리 면과 분홍 몸체가 있는 코딩 인형뽑기 기계.
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { PNG } from 'pngjs';
import { Grid, polygon, rounded, saveHires, root } from './c12-common.mjs';
function machine(f){
 const g=new Grid(64,96);
 // 두 면과 받침은 한 모서리의 2:1 기울기를 이어 가요. 발은 x32,y92예요.
 polygon(g,[[4,18],[32,32],[32,92],[4,78]],'P','s');
 polygon(g,[[32,32],[60,18],[60,78],[32,92]],'R','s');
 g.poly([[5,21],[8,22],[8,76],[30,87],[30,90],[5,77]],'p');
 g.poly([[34,34],[57,22],[57,76],[34,87]],'u');
 g.line(6,76,30,88,'p').line(34,88,58,76,'P');
 // 유리 상자는 크림 프레임과 청록색 면으로 입체를 드러내요.
 polygon(g,[[7,26],[29,37],[29,66],[7,55]],'b','n');
 polygon(g,[[35,37],[57,26],[57,55],[35,66]],'o','m');
 g.poly([[9,28],[27,37],[27,43],[9,34]],'q');
 g.poly([[37,38],[55,29],[55,36],[37,45]],'C');
 // 상자 속 바닥은 인형 아래에 놓인 실제 바닥이며 지면 그림자가 아니에요.
 g.poly([[8,52],[29,62],[29,65],[8,55]],'/');
 g.poly([[35,62],[56,52],[56,55],[35,65]],'n');
 // 줄과 오므리지 않은 세 갈래 집게. 위쪽 레일에 실제로 이어져 있어요.
 g.line(11,30,27,38,'i').line(12,30,27,37,'j');
 g.line(20,34,20,41,'d').line(21,35,21,41,'j');
 rounded(g,17,40,8,4,'i','d');g.line(18,41,22,41,'j');
 g.line(18,44,15,47,'d').line(15,47,16,50,'d').line(19,44,16,47,'a').set(17,49,'a');
 g.line(23,44,26,47,'d').line(26,47,25,50,'d').line(22,44,25,47,'j').set(24,49,'a');
 g.line(20,44,20,48,'f').set(20,49,'a');
 // 작은 잎 슬라임 인형. 같은 섬 친구의 단순한 봉제 실루엣이에요.
 g.ellipse(14,53,6,5,'F').ellipse(14,52,5,4,'J').ellipse(12,50,2,1,'M');
 g.poly([[14,48],[15,45],[18,44],[18,47]],'c').line(15,47,17,45,'L');
 g.set(12,52,'O').set(16,52,'O').line(13,54,15,54,'F');g.line(10,56,12,57,'I');
 // 작은 로비 인형은 안테나, 네모 화면과 둥근 몸으로 구별해요.
 g.rect(24,49,2,3,'Y').set(24,49,'y');
 rounded(g,20,52,10,7,'a','d');g.rect(22,54,6,3,'N').set(23,55,'c').set(26,55,'c');
 rounded(g,21,59,8,5,'i','d');g.rect(23,60,4,2,'C');
 // 오른쪽의 보라 박쥐 인형은 펼친 날개와 짧은 귀가 보여요.
 g.poly([[43,49],[37,48],[38,54],[43,55]],'N').poly([[48,49],[54,46],[53,53],[48,55]],'N');
 g.line(39,50,42,52,'v').line(50,51,52,49,'v');
 g.ellipse(46,53,5,6,'N').ellipse(46,52,4,5,'V').ellipse(45,50,2,2,'v');
 g.poly([[42,49],[42,45],[45,48]],'V').poly([[47,48],[50,45],[50,50]],'V');
 g.set(44,52,'O').set(48,52,'O').line(45,55,47,55,'p');
 // 반사광은 인형 눈과 집게를 피해 유리 가장자리 두 곳에만 넣어요.
 g.line(10,36,14,34,'W').line(10,39,16,36,'q');
 g.line(51,33,55,29,'q').line(53,36,55,34,'b');
 // 굵은 모서리 프레임. 가운데 기둥은 두 면의 경계예요.
 polygon(g,[[3,23],[7,25],[7,56],[3,54]],'p','s');g.line(4,26,4,51,'W');
 polygon(g,[[29,35],[32,36],[35,35],[35,67],[32,69],[29,67]],'p','s');g.line(30,38,30,64,'W').line(33,38,33,65,'P');
 polygon(g,[[57,25],[61,23],[61,54],[57,56]],'u','s');g.line(58,28,58,52,'p');
 polygon(g,[[3,54],[32,68],[61,54],[61,59],[32,73],[3,59]],'P','s');
 g.line(5,55,31,68,'p').line(34,68,59,55,'r');
 // 앞쪽의 큰 인형 출구. 카드·동전 투입구와 조작 버튼은 만들지 않아요.
 polygon(g,[[10,65],[25,72],[25,85],[10,78]],'p','s');
 polygon(g,[[12,68],[23,73],[23,82],[12,77]],'O','d');
 g.poly([[13,75],[23,80],[23,82],[13,77]],'N');
 polygon(g,[[10,77],[25,84],[25,87],[10,80]],'p','s');g.line(11,78,23,84,'W');
 // 반대쪽의 하트 천 장식은 패널이나 돈 투입구로 보이지 않는 큰 색면이에요.
 g.poly([[42,74],[42,71],[44,69],[46,70],[47,72],[49,68],[51,68],[53,70],[52,74],[47,80]],'p');g.line(43,72,44,70,'W').line(49,69,51,69,'x').line(47,78,50,75,'P');
 // 간판의 입체 테두리와 유리처럼 밝은 중앙 표식. 빛 중심은 y13이에요.
 polygon(g,[[3,14],[32,0],[61,14],[32,29]],'p','s');
 polygon(g,[[3,14],[32,29],[32,35],[3,20]],'P','s');
 polygon(g,[[32,29],[61,14],[61,20],[32,35]],'R','s');
 g.line(5,14,31,1,'p').line(4,15,31,29,'W').line(34,29,59,16,'r');
 polygon(g,[[15,13],[32,5],[49,13],[32,22]],f?'o':'C','n');
 g.poly([[18,13],[32,6],[45,13],[32,20]],f?'b':'q');
 // 간판 안의 집게 무늬에는 글자나 돈 기호가 없어요.
 g.line(32,8,32,11,'n').line(28,12,36,12,'n');
 g.line(28,12,26,15,'n').line(26,15,29,17,'n');g.line(36,12,38,15,'n').line(38,15,35,17,'n');
 g.line(32,12,32,16,'n').set(32,17,'W');
 // 좌우 전구 묶음이 번갈아 밝아지고, 구조와 집게/인형은 고정돼요.
 for(const[x,y,left]of[[10,21,true],[22,27,true],[42,27,false],[54,21,false]]){
  const on=left?(f===0):(f===1);g.ellipse(x,y,2,2,on?'y':'R').set(x,y,on?'W':'P');
 }
 return g;
}
const frames=[machine(0),machine(1)];saveHires('prop-claw-machine',frames);
const colors=JSON.parse(readFileSync(root+'assets-src/palette.json','utf8')).colors;
const sw=820,sh=332,sheet=new PNG({width:sw,height:sh});
for(let i=0;i<sheet.data.length;i+=4)sheet.data.set([38,44,59,255],i);
for(let y=0;y<sh;y++)for(let x=410;x<sw;x++)sheet.data.set([255,244,210,255],(y*sw+x)*4);
for(const[ox,scale]of[[10,3],[420,3]])frames.forEach((g,f)=>g.rows.forEach((row,y)=>row.forEach((c,x)=>{if(c==='.')return;const rgb=[1,3,5].map(i=>parseInt(colors[c].slice(i,i+2),16));for(let dy=0;dy<scale;dy++)for(let dx=0;dx<scale;dx++)sheet.data.set([...rgb,255],((18+y*scale+dy)*sw+ox+(f*g.w+x)*scale+dx)*4);})));
mkdirSync(root+'assets-preview/',{recursive:true});writeFileSync(root+'assets-preview/c13-2-machine.png',PNG.sync.write(sheet));
console.log('C13-2 인형뽑기 기계 1키 / 2프레임 생성');

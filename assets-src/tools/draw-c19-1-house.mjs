  g.ellipse(51,62,2,3,'K').line(50,60,51,59,'W');
  g.ellipse(46,73,3,2,'T').line(45,72,46,71,'W');
  g.rect(50,68,4,4,'P').line(50,68,53,68,'p').line(49,73,54,71,'a');

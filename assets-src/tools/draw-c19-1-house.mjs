  polygon(g, [[40,60],[57,51],[57,74],[40,83]], 'U', 'Q');
  g.poly([[42,61],[55,54],[55,72],[42,79]],on?'y':'d');
  g.line(43,70,54,64,'U').line(43,78,54,72,'U');

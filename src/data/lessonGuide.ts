export interface LessonPartGuide {
  part: string;
  /** 도입 5분에 함께 생각할 질문 */
  opening: string[];
  /** 정리 10분에 경험을 돌아볼 질문 */
  closing: string[];
  /** 수업 중 살펴볼 오해나 행동 */
  watch: string;
}

/** 교사가 실제 AI로 보여 주는 시연 한 단계 */
export interface LessonDemoStep {
  title: string;
  /** 교사가 실제 AI에 입력할 부탁(차례대로) */
  ask: string[];
  /** 학생과 함께 볼 점 */
  look: string;
}

export interface LessonDemo {
  intro: string;
  steps: LessonDemoStep[];
  /** 시연 전에 지킬 점 */
  safety: string[];
}

/** 인쇄해서 나눠 줄 학생 기록지(첫 칸만 채운 빈 표) */
export interface LessonWorksheet {
  title: string;
  intro: string;
  tables: { title: string; columns: string[]; rows: string[] }[];
  /** □ 표시로 스스로 확인할 것 */
  checks: string[];
}

